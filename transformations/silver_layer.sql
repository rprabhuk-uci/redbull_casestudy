UNION ALL
SELECT 'MATCHING', COUNT(*) FROM SILVER.MATCHING
UNION ALL
SELECT 'MATCHING_QUARANTINE', COUNT(*) FROM SILVER.MATCHING_QUARANTINE
UNION ALL
SELECT 'PORTFOLIO', COUNT(*) FROM SILVER.PORTFOLIO
UNION ALL
SELECT 'PORTFOLIO_QUARANTINE', COUNT(*) FROM SILVER.PORTFOLIO_QUARANTINE;